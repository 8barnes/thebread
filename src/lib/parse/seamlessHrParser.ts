/**
 * REAL SEAMLESSHR MULTI-PAGE STREAM PARSER
 *
 * Implements the battle-tested extraction engine for real Pinnacle Group/RCPL
 * SeamlessHR appraisal PDFs.
 *
 * Handles:
 *  - Vertically stacked fields ("Target\n100\nActual\n100...")
 *  - Letter-spaced cover-page headers ("E M P L O Y E E I D", "J O B R O L E")
 *  - Repeated per-page footer boilerplate stripping
 *  - Page-offset tracking across page boundaries
 *  - Full 8-type taxonomy mapping from "Type N"
 *  - Lead-clause KPI type inference
 *  - Appraisal-level comments with timestamp, role, department, and text
 *  - Multi-signatory extraction (Reviewer, Counter Signing, ARC)
 */

